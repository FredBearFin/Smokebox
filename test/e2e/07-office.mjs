async function pageReady(page, id) {
  await page.waitForFunction((id) => { const o = document.querySelector('#sb-office .of'); const m = document.querySelector('#sb-office .of-main'); return !!(o && m && (o.dataset.page === id || !o.dataset.page)); }, id, { timeout: 10000 }).catch(() => {});
  await wait(550);
}
async function go(page, id) {
  // a person clicks the rail; fall back to the address bar when the office is not open yet or the rail link is not on screen
  const link = page.locator('#sb-office a.of-nav[data-page="' + id + '"]');
  if ((await officeOpen(page)) && (await link.count()) && (await link.isVisible().catch(() => false))) await link.click().catch(() => {});
  else await page.evaluate((id) => { location.hash = '#/office/' + id; }, id);
  if (!(await officeOpen(page))) await waitOffice(page, 6000);
  await pageReady(page, id);
}
const seg = (page, label) => page.locator('#sb-office').getByRole('radio', { name: label, exact: true }).first();
async function choose(page, label) { await seg(page, label).click(); await wait(450); }
const tileVal = async (page, id) => (await page.locator('#sb-office .of-tile[data-id="' + id + '"] .of-tile-val').first().textContent().catch(() => '')).replace(/\s+/g, ' ').trim();

/** Everything we can say about the office page that is showing. */
async function auditPage(t, page, id, label, { noData = false } = {}) {
  const owner = OWN[id];
  const text = await officeText(page);
  const bad = text.match(BAD_TEXT);
  t.check(label + ': text has no NaN / undefined / Infinity / null / [object Object]', !bad, bad && text.slice(Math.max(0, bad.index - 60), bad.index + 60).replace(/\s+/g, ' '), owner);
  const errs = await page.locator('#sb-office .of-error').count();
  t.check(label + ': no "could not be drawn" error card', errs === 0, await page.locator('#sb-office .of-error').allInnerTexts(), owner);
  t.check(label + ': the page has some content (more than 150 characters)', text.length > 150, text.length, owner);
  const charts = (await chartAudit(page)).filter((c) => c.w > 0 && c.h > 0 && c.hasCard); // sparklines in the number tiles have no card of their own
  const emptyFrames = charts.filter((c) => !c.table && c.marks === 0 && !c.hasEmptyMsg);
  t.check(label + ': no empty chart frames (a chart with no marks must say "Not enough data")', emptyFrames.length === 0, emptyFrames.map((c) => c.name + ' [' + c.type + ']'), owner);
  if (!noData && id !== 'data') {
    t.check(label + ': at least one chart is drawn with marks', charts.some((c) => c.marks > 0), charts.map((c) => c.name + ':' + c.marks), owner);
    const noLook = charts.filter((c) => !c.hasLook);
    t.check(label + ': every chart card has a "What to look for" sentence', noLook.length === 0, noLook.map((c) => c.name), owner);
    const noTbl = charts.filter((c) => c.marks > 0 && !c.hasTableBtn && c.type !== 'spark');
    t.check(label + ': every drawn chart offers View as table', noTbl.length === 0, noTbl.map((c) => c.name + ' [' + c.type + ']'), owner);
  }
  if (noData && id !== 'data') {
    t.check(label + ': says "Not enough data" somewhere instead of drawing zeros', /Not enough data|No tickets|nothing|No finished|not enough|No (sales|food-safety|stock)|first (order|batch)/i.test(text), text.slice(0, 200), owner);
  }
  if (id !== 'data') {
    const head = await page.locator('#sb-office .of-headline').first().innerText().catch(() => '');
    t.check(label + ': opens with a plain headline sentence', head.length > 15, head, owner);
  }
  const banner = await page.locator('#sb-office .of-banner').first().innerText().catch(() => '');
  t.check(label + ': the data banner is present', banner.length > 10, banner, 'officeA');
  return { text, charts, banner };
}

